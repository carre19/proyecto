-- =====================================================================================================
-- Fase 4: RRPP. Talonarios (cada RRPP tiene su link de venta y entradas asignadas), listas de invitados,
-- comisión por venta y resultados. Se aplica después de la fase 3; se puede repetir.
-- =====================================================================================================
BEGIN;

-- El talonario de un RRPP para un evento: las entradas que se le asignaron y su link propio (codigo). Las compras hechas con ese
-- link se le adjudican a él. Hay uno por RRPP y evento: para darle más entradas se sube la cantidad.
CREATE TABLE IF NOT EXISTS public.talonario (
    id_talonario integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_boliche integer NOT NULL,
    id_evento integer NOT NULL,
    id_rrpp integer NOT NULL,
    codigo character varying(12) NOT NULL,
    cantidad integer NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    creado_por integer,
    creado_en timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT talonario_pkey PRIMARY KEY (id_talonario),
    CONSTRAINT talonario_boliche_talonario_key UNIQUE (id_boliche, id_talonario),
    CONSTRAINT talonario_codigo_key UNIQUE (codigo),
    CONSTRAINT talonario_evento_rrpp_key UNIQUE (id_evento, id_rrpp),
    CONSTRAINT talonario_evento_fkey FOREIGN KEY (id_boliche, id_evento) REFERENCES public.evento(id_boliche, id_evento) ON DELETE CASCADE,
    CONSTRAINT talonario_rrpp_fkey FOREIGN KEY (id_boliche, id_rrpp) REFERENCES public.boliche_equipo(id_boliche, id_usuario) ON DELETE CASCADE,
    CONSTRAINT talonario_creador_fkey FOREIGN KEY (creado_por) REFERENCES public.usuario(id_usuario) ON DELETE SET NULL,
    CONSTRAINT chk_talonario_cantidad CHECK (cantidad > 0)
);

-- La compra hecha con el link de un talonario queda atada a él (para contar cuánto se vendió de lo asignado).
ALTER TABLE public.compra ADD COLUMN IF NOT EXISTS id_talonario integer;
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'compra_talonario_fkey') THEN
        ALTER TABLE public.compra ADD CONSTRAINT compra_talonario_fkey FOREIGN KEY (id_boliche, id_talonario)
            REFERENCES public.talonario(id_boliche, id_talonario) ON DELETE SET NULL (id_talonario);
    END IF;
END $$;
CREATE INDEX IF NOT EXISTS compra_talonario_idx ON public.compra (id_talonario) WHERE id_talonario IS NOT NULL;

-- Listas de invitados que arma cada RRPP para un evento. Cada invitado lleva nombre, apellido, DNI, teléfono y edad.
CREATE TABLE IF NOT EXISTS public.lista_invitados (
    id_lista integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_boliche integer NOT NULL,
    id_evento integer NOT NULL,
    id_rrpp integer NOT NULL,
    nombre character varying(100) NOT NULL,
    creada_en timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT lista_invitados_pkey PRIMARY KEY (id_lista),
    CONSTRAINT lista_invitados_boliche_lista_key UNIQUE (id_boliche, id_lista),
    CONSTRAINT lista_evento_fkey FOREIGN KEY (id_boliche, id_evento) REFERENCES public.evento(id_boliche, id_evento) ON DELETE CASCADE,
    CONSTRAINT lista_rrpp_fkey FOREIGN KEY (id_boliche, id_rrpp) REFERENCES public.boliche_equipo(id_boliche, id_usuario) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS lista_evento_idx ON public.lista_invitados (id_boliche, id_evento);

CREATE TABLE IF NOT EXISTS public.invitado (
    id_invitado integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_boliche integer NOT NULL,
    id_evento integer NOT NULL,
    id_lista integer NOT NULL,
    nombre character varying(100) NOT NULL,
    apellido character varying(100) NOT NULL,
    dni character varying(15) NOT NULL,
    telefono character varying(30),
    edad smallint NOT NULL,
    ingreso_en timestamp with time zone,
    ingreso_por integer,
    CONSTRAINT invitado_pkey PRIMARY KEY (id_invitado),
    CONSTRAINT invitado_lista_fkey FOREIGN KEY (id_boliche, id_lista) REFERENCES public.lista_invitados(id_boliche, id_lista) ON DELETE CASCADE,
    CONSTRAINT invitado_ingreso_fkey FOREIGN KEY (ingreso_por) REFERENCES public.usuario(id_usuario) ON DELETE SET NULL,
    CONSTRAINT chk_invitado_dni CHECK (dni ~ '^[0-9]{7,9}$'),
    CONSTRAINT chk_invitado_edad CHECK (edad BETWEEN 0 AND 120)
);
-- Una persona (DNI) figura una sola vez en las listas de un evento.
CREATE UNIQUE INDEX IF NOT EXISTS invitado_dni_evento_key ON public.invitado (id_evento, dni);
CREATE INDEX IF NOT EXISTS invitado_lista_idx ON public.invitado (id_lista);

-- El invitado tiene que ser del mismo evento que su lista, y tener la edad mínima del evento.
CREATE OR REPLACE FUNCTION public.validar_invitado() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    evento_lista integer;
    minima smallint;
BEGIN
    SELECT l.id_evento, e.edad_minima INTO evento_lista, minima
      FROM public.lista_invitados l JOIN public.evento e ON e.id_boliche = l.id_boliche AND e.id_evento = l.id_evento
     WHERE l.id_boliche = NEW.id_boliche AND l.id_lista = NEW.id_lista;
    IF evento_lista IS NULL OR evento_lista <> NEW.id_evento THEN
        RAISE EXCEPTION 'El invitado tiene que ser del mismo evento que su lista';
    END IF;
    IF NEW.edad < minima THEN
        RAISE EXCEPTION 'La edad mínima de este evento es % años', minima;
    END IF;
    RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_validar_invitado ON public.invitado;
CREATE TRIGGER trg_validar_invitado BEFORE INSERT OR UPDATE OF edad, id_lista ON public.invitado
    FOR EACH ROW EXECUTE FUNCTION public.validar_invitado();

-- La puerta también registra a los invitados de lista que entran.
ALTER TABLE public.acceso_puerta ADD COLUMN IF NOT EXISTS id_invitado integer;
ALTER TABLE public.acceso_puerta DROP CONSTRAINT IF EXISTS chk_acceso_resultado;
ALTER TABLE public.acceso_puerta ADD CONSTRAINT chk_acceso_resultado CHECK (resultado IN
    ('ingreso', 'reingreso', 'ingreso_lista', 'rechazada_usada', 'rechazada_no_pagada', 'rechazada_anulada', 'rechazada_otro_evento', 'no_encontrada'));

COMMIT;
