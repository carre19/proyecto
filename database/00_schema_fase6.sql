-- =====================================================================================================
-- Fase 6: descuentos para clientes con cuenta, verificación en dos pasos de los admins, borrado de datos personales a los 3 meses
-- y cobros de la plataforma a los boliches (mensualidades y eventos únicos). Se aplica después de la fase 5; se puede repetir.
-- =====================================================================================================
BEGIN;

-- Descuentos que define cada admin para los clientes que tienen cuenta. Se aplican a las compras hechas desde la página:
-- el cliente con cuenta de más de "antiguedad_meses" meses recibe el mayor descuento que le corresponda (no se acumulan).
-- Ejemplo: un cliente registrado hace más de 6 meses recibe un 5 % al pagar por transferencia.
CREATE TABLE IF NOT EXISTS public.descuento (
    id_descuento integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_boliche integer NOT NULL,
    nombre character varying(100) NOT NULL,
    porcentaje numeric(5, 2) NOT NULL,
    antiguedad_meses smallint NOT NULL DEFAULT 0,
    activo boolean NOT NULL DEFAULT true,
    CONSTRAINT descuento_pkey PRIMARY KEY (id_descuento),
    CONSTRAINT descuento_boliche_fkey FOREIGN KEY (id_boliche) REFERENCES public.boliche(id_boliche) ON DELETE CASCADE,
    CONSTRAINT chk_descuento_porcentaje CHECK (porcentaje > 0 AND porcentaje <= 100),
    CONSTRAINT chk_descuento_antiguedad CHECK (antiguedad_meses >= 0 AND antiguedad_meses <= 240)
);

-- Qué descuento se le aplicó a una compra (para mostrarlo; el monto está en compra.descuento).
ALTER TABLE public.compra ADD COLUMN IF NOT EXISTS descuento_nombre character varying(100);

-- Verificación en dos pasos (código de 6 números de una app como Google Authenticator). El secreto se guarda cifrado.
-- totp_ultimo_paso evita que el mismo código se use dos veces.
ALTER TABLE public.usuario ADD COLUMN IF NOT EXISTS totp_secreto character varying(200);
ALTER TABLE public.usuario ADD COLUMN IF NOT EXISTS totp_activo boolean NOT NULL DEFAULT false;
ALTER TABLE public.usuario ADD COLUMN IF NOT EXISTS totp_ultimo_paso bigint;

-- Códigos de recuperación (de un solo uso) por si se pierde el celular. Solo se guarda su huella.
CREATE TABLE IF NOT EXISTS public.usuario_recuperacion (
    id_usuario integer NOT NULL,
    huella character varying(64) NOT NULL,
    usado_en timestamp with time zone,
    CONSTRAINT usuario_recuperacion_pkey PRIMARY KEY (id_usuario, huella),
    CONSTRAINT usuario_recuperacion_usuario_fkey FOREIGN KEY (id_usuario) REFERENCES public.usuario(id_usuario) ON DELETE CASCADE
);

-- Borrado de datos personales: cuando pasan 3 meses sin que la persona compre ni interactúe, se borran su nombre, DNI y contacto.
-- Lo económico (precios, comisiones, pagos) se conserva para la contabilidad. datos_borrados_en marca lo ya anonimizado.
ALTER TABLE public.entrada ADD COLUMN IF NOT EXISTS datos_borrados_en timestamp with time zone;
ALTER TABLE public.compra ADD COLUMN IF NOT EXISTS datos_borrados_en timestamp with time zone;
ALTER TABLE public.invitado ADD COLUMN IF NOT EXISTS datos_borrados_en timestamp with time zone;
ALTER TABLE public.notificacion ADD COLUMN IF NOT EXISTS datos_borrados_en timestamp with time zone;
-- Al borrar el nombre no puede quedar un DNI repetido: el sistema lo reemplaza por un número único que no es de nadie.
-- Esas entradas ya no existen para la puerta; el DNI deja de ser obligatorio solo en el formato (7 a 9 números se mantiene).

-- Cobros de la plataforma a cada boliche: la mensualidad (un cobro por mes) o, si el boliche es de un solo evento,
-- un cobro por ese evento (sin mensualidad). Los carga el superadmin y los marca pagados cuando cobra.
CREATE TABLE IF NOT EXISTS public.cobro_plataforma (
    id_cobro integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_boliche integer NOT NULL,
    tipo character varying(15) NOT NULL,
    periodo date,
    id_evento integer,
    monto integer NOT NULL,
    estado character varying(10) NOT NULL DEFAULT 'pendiente',
    nota character varying(300),
    generado_en timestamp with time zone NOT NULL DEFAULT now(),
    pagado_en timestamp with time zone,
    CONSTRAINT cobro_plataforma_pkey PRIMARY KEY (id_cobro),
    CONSTRAINT cobro_boliche_fkey FOREIGN KEY (id_boliche) REFERENCES public.boliche(id_boliche) ON DELETE CASCADE,
    CONSTRAINT cobro_evento_fkey FOREIGN KEY (id_boliche, id_evento) REFERENCES public.evento(id_boliche, id_evento) ON DELETE SET NULL (id_evento),
    CONSTRAINT chk_cobro_tipo CHECK (tipo IN ('mensualidad', 'evento_unico')),
    CONSTRAINT chk_cobro_estado CHECK (estado IN ('pendiente', 'pagado')),
    CONSTRAINT chk_cobro_monto CHECK (monto >= 0),
    CONSTRAINT chk_cobro_periodo CHECK (tipo <> 'mensualidad' OR (periodo IS NOT NULL AND extract(day FROM periodo) = 1))
);
CREATE UNIQUE INDEX IF NOT EXISTS cobro_mensualidad_key ON public.cobro_plataforma (id_boliche, periodo) WHERE tipo = 'mensualidad';
CREATE UNIQUE INDEX IF NOT EXISTS cobro_evento_key ON public.cobro_plataforma (id_boliche, id_evento) WHERE tipo = 'evento_unico' AND id_evento IS NOT NULL;
CREATE INDEX IF NOT EXISTS cobro_estado_idx ON public.cobro_plataforma (estado, generado_en DESC);

COMMIT;
