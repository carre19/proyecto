-- Fase 2: venta de entradas (compra con nombre, apellido y DNI), QR de un solo uso y control en puerta.
-- Se aplica DESPUÉS de 00_schema.sql y se puede correr más de una vez (no pisa nada).
-- Todo lo que cuelga de un boliche lleva id_boliche y claves compuestas, igual que el resto del esquema.
-- Precios en pesos enteros.
-- =====================================================================================================
BEGIN;

-- Hace falta para poder referenciar una entrada de un evento con la clave compuesta (boliche, evento, tipo).
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'tipo_entrada_evento_tipo_key') THEN
        ALTER TABLE public.tipo_entrada ADD CONSTRAINT tipo_entrada_evento_tipo_key UNIQUE (id_boliche, id_evento, id_tipo_entrada);
    END IF;
END $$;

-- "agotada_auto": la entrada se marcó agotada sola porque se vendió todo el cupo (si se libera cupo, vuelve a estar disponible).
-- Si el admin la marca agotada a mano, no se toca.
ALTER TABLE public.tipo_entrada ADD COLUMN IF NOT EXISTS agotada_auto boolean NOT NULL DEFAULT false;

-- Una compra puede traer varias entradas (una por persona). canal: 'web' (desde la página, precio virtual) o 'puerta' (en el local).
-- Pendiente: espera el pago hasta vence_en; si no se paga, se cancela sola y el cupo se libera.
CREATE TABLE IF NOT EXISTS public.compra (
    id_compra integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_boliche integer NOT NULL,
    id_evento integer NOT NULL,
    id_cliente integer,
    token_publico character varying(40) NOT NULL,
    referencia character varying(12) NOT NULL,
    canal character varying(10) NOT NULL DEFAULT 'web',
    metodo_pago character varying(15) NOT NULL DEFAULT 'transferencia',
    estado character varying(10) NOT NULL DEFAULT 'pendiente',
    id_vendedor integer,
    id_rrpp integer,
    subtotal integer NOT NULL,
    descuento integer NOT NULL DEFAULT 0,
    cargo_plataforma integer NOT NULL DEFAULT 0,
    total integer NOT NULL,
    contacto_email character varying(150),
    contacto_telefono character varying(30),
    creada_en timestamp with time zone NOT NULL DEFAULT now(),
    vence_en timestamp with time zone,
    pagada_en timestamp with time zone,
    CONSTRAINT compra_pkey PRIMARY KEY (id_compra),
    CONSTRAINT compra_boliche_compra_key UNIQUE (id_boliche, id_compra),
    CONSTRAINT compra_token_key UNIQUE (token_publico),
    CONSTRAINT compra_referencia_key UNIQUE (referencia),
    CONSTRAINT compra_evento_fkey FOREIGN KEY (id_boliche, id_evento) REFERENCES public.evento(id_boliche, id_evento),
    CONSTRAINT compra_cliente_fkey FOREIGN KEY (id_cliente) REFERENCES public.usuario(id_usuario) ON DELETE SET NULL,
    CONSTRAINT compra_vendedor_fkey FOREIGN KEY (id_vendedor) REFERENCES public.usuario(id_usuario) ON DELETE SET NULL,
    CONSTRAINT compra_rrpp_fkey FOREIGN KEY (id_boliche, id_rrpp) REFERENCES public.boliche_equipo(id_boliche, id_usuario) ON DELETE SET NULL (id_rrpp),
    CONSTRAINT chk_compra_canal CHECK (canal IN ('web', 'puerta')),
    CONSTRAINT chk_compra_metodo CHECK (metodo_pago IN ('transferencia', 'efectivo', 'qr')),
    CONSTRAINT chk_compra_estado CHECK (estado IN ('pendiente', 'pagada', 'cancelada')),
    CONSTRAINT chk_compra_montos CHECK (subtotal >= 0 AND descuento >= 0 AND cargo_plataforma >= 0 AND total >= 0 AND descuento <= subtotal)
);
CREATE INDEX IF NOT EXISTS compra_evento_idx ON public.compra (id_boliche, id_evento, estado);
CREATE INDEX IF NOT EXISTS compra_cliente_idx ON public.compra (id_cliente) WHERE id_cliente IS NOT NULL;

-- Una entrada por persona. "codigo" es lo que lleva el QR y sirve UNA sola vez. Lleva escrito el DNI de la persona.
-- pendiente (sin pagar) -> valida (pagada) -> usada (ya entró) | anulada (compra cancelada o vencida).
CREATE TABLE IF NOT EXISTS public.entrada (
    id_entrada integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_boliche integer NOT NULL,
    id_evento integer NOT NULL,
    id_tipo_entrada integer NOT NULL,
    id_compra integer NOT NULL,
    nombre character varying(100) NOT NULL,
    apellido character varying(100) NOT NULL,
    dni character varying(15) NOT NULL,
    precio integer NOT NULL,
    codigo character varying(32) NOT NULL,
    estado character varying(10) NOT NULL DEFAULT 'pendiente',
    usada_en timestamp with time zone,
    id_rrpp integer,
    comision_pct numeric(5, 2),
    comision integer,
    CONSTRAINT entrada_pkey PRIMARY KEY (id_entrada),
    CONSTRAINT entrada_boliche_entrada_key UNIQUE (id_boliche, id_entrada),
    CONSTRAINT entrada_codigo_key UNIQUE (codigo),
    CONSTRAINT entrada_tipo_fkey FOREIGN KEY (id_boliche, id_evento, id_tipo_entrada) REFERENCES public.tipo_entrada(id_boliche, id_evento, id_tipo_entrada),
    CONSTRAINT entrada_compra_fkey FOREIGN KEY (id_boliche, id_compra) REFERENCES public.compra(id_boliche, id_compra) ON DELETE CASCADE,
    CONSTRAINT entrada_rrpp_fkey FOREIGN KEY (id_boliche, id_rrpp) REFERENCES public.boliche_equipo(id_boliche, id_usuario) ON DELETE SET NULL (id_rrpp),
    CONSTRAINT chk_entrada_estado CHECK (estado IN ('pendiente', 'valida', 'usada', 'anulada')),
    CONSTRAINT chk_entrada_dni CHECK (dni ~ '^[0-9]{7,9}$'),
    CONSTRAINT chk_entrada_precio CHECK (precio >= 0)
);
CREATE INDEX IF NOT EXISTS entrada_compra_idx ON public.entrada (id_compra);
CREATE INDEX IF NOT EXISTS entrada_evento_idx ON public.entrada (id_boliche, id_evento, estado);
-- La entrada es personal: una persona (DNI) no puede tener dos entradas vigentes para el mismo evento.
CREATE UNIQUE INDEX IF NOT EXISTS entrada_dni_evento_key ON public.entrada (id_evento, dni) WHERE estado <> 'anulada';

-- Registro de lo que pasa en la puerta (para saber quién dejó entrar a quién y por qué se rechazó una entrada).
CREATE TABLE IF NOT EXISTS public.acceso_puerta (
    id_acceso integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_boliche integer NOT NULL,
    id_evento integer NOT NULL,
    id_entrada integer,
    resultado character varying(25) NOT NULL,
    id_usuario integer,
    momento timestamp with time zone NOT NULL DEFAULT now(),
    detalle character varying(200),
    CONSTRAINT acceso_puerta_pkey PRIMARY KEY (id_acceso),
    CONSTRAINT acceso_evento_fkey FOREIGN KEY (id_boliche, id_evento) REFERENCES public.evento(id_boliche, id_evento) ON DELETE CASCADE,
    CONSTRAINT acceso_usuario_fkey FOREIGN KEY (id_usuario) REFERENCES public.usuario(id_usuario) ON DELETE SET NULL,
    CONSTRAINT chk_acceso_resultado CHECK (resultado IN ('ingreso', 'reingreso', 'rechazada_usada', 'rechazada_no_pagada', 'rechazada_anulada', 'rechazada_otro_evento', 'no_encontrada'))
);
CREATE INDEX IF NOT EXISTS acceso_evento_idx ON public.acceso_puerta (id_boliche, id_evento, momento DESC);

-- No se pueden vender más entradas que el cupo de cada tipo (el servidor además bloquea la fila para que dos compras
-- al mismo tiempo no se pasen).
CREATE OR REPLACE FUNCTION public.validar_cupo_venta() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    cupo_tipo integer;
    vendidas integer;
BEGIN
    IF NEW.estado = 'anulada' THEN
        RETURN NEW;
    END IF;
    SELECT t.cupo INTO cupo_tipo FROM public.tipo_entrada t WHERE t.id_tipo_entrada = NEW.id_tipo_entrada;
    SELECT count(*) INTO vendidas FROM public.entrada e WHERE e.id_tipo_entrada = NEW.id_tipo_entrada AND e.estado <> 'anulada';
    IF vendidas >= cupo_tipo THEN
        RAISE EXCEPTION 'No quedan entradas de este tipo (cupo %)', cupo_tipo;
    END IF;
    RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_validar_cupo_venta ON public.entrada;
CREATE TRIGGER trg_validar_cupo_venta BEFORE INSERT ON public.entrada
    FOR EACH ROW EXECUTE FUNCTION public.validar_cupo_venta();

-- No se puede bajar el cupo de un tipo por debajo de lo que ya se vendió.
CREATE OR REPLACE FUNCTION public.validar_cupo_vendido() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    vendidas integer;
BEGIN
    SELECT count(*) INTO vendidas FROM public.entrada e WHERE e.id_tipo_entrada = NEW.id_tipo_entrada AND e.estado <> 'anulada';
    IF NEW.cupo < vendidas THEN
        RAISE EXCEPTION 'El cupo no puede ser menor a las entradas ya vendidas (%)', vendidas;
    END IF;
    RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_validar_cupo_vendido ON public.tipo_entrada;
CREATE TRIGGER trg_validar_cupo_vendido BEFORE UPDATE OF cupo ON public.tipo_entrada
    FOR EACH ROW EXECUTE FUNCTION public.validar_cupo_vendido();

-- Cancela las compras que no se pagaron a tiempo y libera sus entradas. Devuelve cuántas canceló.
CREATE OR REPLACE FUNCTION public.liberar_compras_vencidas() RETURNS integer LANGUAGE plpgsql AS $$
DECLARE
    cantidad integer;
BEGIN
    UPDATE public.entrada SET estado = 'anulada'
     WHERE estado = 'pendiente' AND id_compra IN (SELECT id_compra FROM public.compra WHERE estado = 'pendiente' AND vence_en < now());
    UPDATE public.compra SET estado = 'cancelada' WHERE estado = 'pendiente' AND vence_en < now();
    GET DIAGNOSTICS cantidad = ROW_COUNT;
    RETURN cantidad;
END $$;

COMMIT;
