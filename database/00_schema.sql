-- =====================================================
-- ESQUEMA DE LA PLATAFORMA DE BOLICHES Y BARES
-- Un solo sistema para muchos locales. Cada local ve únicamente lo suyo: por eso toda tabla de un
-- local lleva id_boliche, y las claves foráneas compuestas (id_boliche + id) impiden que algo de
-- un local quede enganchado a otro, aunque el código tenga un error.
-- Roles (un usuario tiene uno): superadmin, admin, rrpp_manager, rrpp, cliente.
-- Las fases siguientes (entradas, pagos, listas, personal externo, finanzas) suman tablas con el mismo criterio.
-- =====================================================

BEGIN;

-- =====================================================
-- 1. USUARIOS
-- El rol define el panel. Admin, RRPP y clientes inician sesión con email y contraseña (bcrypt).
-- ultima_actividad sirve para borrar los datos de los clientes inactivos (a los 3 meses).
-- =====================================================

CREATE TABLE public.usuario (
    id_usuario integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    email character varying(150) NOT NULL,
    password_hash character varying(100) NOT NULL,
    nombre character varying(100) NOT NULL,
    apellido character varying(100) NOT NULL,
    nombre_completo character varying(201) GENERATED ALWAYS AS (nombre || ' ' || apellido) STORED,
    dni character varying(15),
    telefono character varying(30),
    rol character varying(20) NOT NULL DEFAULT 'cliente',
    activo boolean NOT NULL DEFAULT true,
    fecha_creacion timestamp with time zone NOT NULL DEFAULT now(),
    ultima_actividad timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT usuario_pkey PRIMARY KEY (id_usuario),
    CONSTRAINT chk_usuario_rol CHECK (rol IN ('superadmin', 'admin', 'rrpp_manager', 'rrpp', 'cliente')),
    CONSTRAINT chk_usuario_email CHECK (email = lower(email))
);

CREATE UNIQUE INDEX usuario_email_key ON public.usuario (email);

-- =====================================================
-- 2. BOLICHES (los locales)
-- Los crea el superadmin. Cada uno tiene su página en un subdominio de la plataforma.
-- La plataforma cobra una mensualidad por boliche (o un monto aparte si es un solo evento) y el 6 % de cada entrada.
-- =====================================================

CREATE TABLE public.boliche (
    id_boliche integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre character varying(120) NOT NULL,
    subdominio character varying(30) NOT NULL,
    descripcion text,
    direccion character varying(200),
    latitud numeric(9, 6),
    longitud numeric(9, 6),
    capacidad integer,
    instagram character varying(100),
    whatsapp character varying(30),
    tipo_cobro character varying(15) NOT NULL DEFAULT 'mensual',
    monto_mensual numeric(12, 2),
    activo boolean NOT NULL DEFAULT true,
    fecha_creacion timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT boliche_pkey PRIMARY KEY (id_boliche),
    CONSTRAINT boliche_subdominio_key UNIQUE (subdominio),
    CONSTRAINT chk_boliche_subdominio CHECK (subdominio ~ '^[a-z0-9][a-z0-9-]{1,28}[a-z0-9]$'),
    CONSTRAINT chk_boliche_capacidad CHECK (capacidad IS NULL OR capacidad > 0),
    CONSTRAINT chk_boliche_tipo_cobro CHECK (tipo_cobro IN ('mensual', 'evento_unico')),
    CONSTRAINT chk_boliche_monto CHECK (monto_mensual IS NULL OR monto_mensual >= 0)
);

-- Un admin puede tener varios boliches y un boliche puede tener varios admins (los dueños).
CREATE TABLE public.boliche_admin (
    id_boliche integer NOT NULL,
    id_usuario integer NOT NULL,
    CONSTRAINT boliche_admin_pkey PRIMARY KEY (id_boliche, id_usuario),
    CONSTRAINT boliche_admin_boliche_fkey FOREIGN KEY (id_boliche) REFERENCES public.boliche(id_boliche) ON DELETE CASCADE,
    CONSTRAINT boliche_admin_usuario_fkey FOREIGN KEY (id_usuario) REFERENCES public.usuario(id_usuario) ON DELETE CASCADE
);

-- El equipo de RRPP de un boliche: el manager (opcional) y los RRPP. Cada uno pertenece a UN solo boliche.
-- La comisión de cada RRPP la fija el admin. Un RRPP puede depender de un manager o ir directo con el admin.
CREATE TABLE public.boliche_equipo (
    id_boliche integer NOT NULL,
    id_usuario integer NOT NULL,
    rol character varying(20) NOT NULL,
    id_manager integer,
    comision_pct numeric(5, 2) NOT NULL DEFAULT 0,
    fecha_alta timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT boliche_equipo_pkey PRIMARY KEY (id_boliche, id_usuario),
    CONSTRAINT boliche_equipo_usuario_key UNIQUE (id_usuario),
    CONSTRAINT boliche_equipo_boliche_fkey FOREIGN KEY (id_boliche) REFERENCES public.boliche(id_boliche) ON DELETE CASCADE,
    CONSTRAINT boliche_equipo_usuario_fkey FOREIGN KEY (id_usuario) REFERENCES public.usuario(id_usuario) ON DELETE CASCADE,
    -- el manager tiene que ser del MISMO boliche (clave compuesta)
    CONSTRAINT boliche_equipo_manager_fkey FOREIGN KEY (id_boliche, id_manager) REFERENCES public.boliche_equipo(id_boliche, id_usuario) ON DELETE SET NULL (id_manager),
    CONSTRAINT chk_equipo_rol CHECK (rol IN ('rrpp_manager', 'rrpp')),
    CONSTRAINT chk_equipo_comision CHECK (comision_pct >= 0 AND comision_pct <= 100),
    CONSTRAINT chk_equipo_manager CHECK (id_manager IS NULL OR rol = 'rrpp')
);

-- =====================================================
-- 3. EVENTOS (la noche de cada boliche)
-- UNIQUE (id_boliche, id_evento) permite que las tablas hijas (tandas, entradas, listas...) lleven
-- id_boliche y que la base garantice que coincide con el del evento.
-- =====================================================

CREATE TABLE public.evento (
    id_evento integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_boliche integer NOT NULL,
    nombre character varying(150) NOT NULL,
    fecha_hora timestamp with time zone NOT NULL,
    artistas text[] NOT NULL DEFAULT '{}',
    edad_minima smallint NOT NULL DEFAULT 18,
    dress_code character varying(100),
    tiene_vip boolean NOT NULL DEFAULT false,
    mesas_vip integer,
    descripcion text,
    imagen character varying(300),
    estado character varying(15) NOT NULL DEFAULT 'publicado',
    id_creador integer,
    fecha_creacion timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT evento_pkey PRIMARY KEY (id_evento),
    CONSTRAINT evento_boliche_evento_key UNIQUE (id_boliche, id_evento),
    CONSTRAINT evento_boliche_fkey FOREIGN KEY (id_boliche) REFERENCES public.boliche(id_boliche) ON DELETE CASCADE,
    CONSTRAINT evento_creador_fkey FOREIGN KEY (id_creador) REFERENCES public.usuario(id_usuario) ON DELETE SET NULL,
    CONSTRAINT chk_evento_estado CHECK (estado IN ('publicado', 'cancelado', 'finalizado')),
    CONSTRAINT chk_evento_edad CHECK (edad_minima BETWEEN 0 AND 99),
    CONSTRAINT chk_evento_mesas CHECK (mesas_vip IS NULL OR (tiene_vip AND mesas_vip >= 0))
);

CREATE INDEX evento_boliche_fecha_idx ON public.evento (id_boliche, fecha_hora);


-- =====================================================
-- 3B. FICHA DEL BOLICHE, ENTRADAS, BEBIDAS, MESAS VIP Y COLORES (fase 1B)
-- Todas llevan id_boliche. Cuando cuelgan de un evento o de una mesa, la clave foránea compuesta
-- (id_boliche + id) garantiza que sean del MISMO boliche, aunque el código tenga un error.
-- Los precios son pesos argentinos, números enteros.
-- =====================================================

-- Fotos de un boliche: una puede ser la portada (solo una por boliche) y el resto forma la galería.
CREATE TABLE public.boliche_foto (
    id_foto integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_boliche integer NOT NULL,
    url character varying(300) NOT NULL,
    es_portada boolean NOT NULL DEFAULT false,
    orden smallint NOT NULL DEFAULT 0,
    fecha_creacion timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT boliche_foto_pkey PRIMARY KEY (id_foto),
    CONSTRAINT boliche_foto_boliche_fkey FOREIGN KEY (id_boliche) REFERENCES public.boliche(id_boliche) ON DELETE CASCADE
);

CREATE UNIQUE INDEX boliche_foto_portada_key ON public.boliche_foto (id_boliche) WHERE es_portada;
CREATE INDEX boliche_foto_boliche_idx ON public.boliche_foto (id_boliche, orden);

-- Las entradas de cada evento: tandas y VIP, con su precio virtual (el que se paga desde la página) y el de puerta.
-- La suma de los cupos de un evento no puede superar la capacidad del boliche (trigger más abajo).
CREATE TABLE public.tipo_entrada (
    id_tipo_entrada integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_boliche integer NOT NULL,
    id_evento integer NOT NULL,
    nombre character varying(60) NOT NULL,
    tipo character varying(5) NOT NULL DEFAULT 'tanda',
    precio_virtual integer NOT NULL,
    precio_puerta integer NOT NULL,
    cupo integer NOT NULL,
    estado character varying(15) NOT NULL DEFAULT 'disponible',
    orden smallint NOT NULL DEFAULT 0,
    CONSTRAINT tipo_entrada_pkey PRIMARY KEY (id_tipo_entrada),
    CONSTRAINT tipo_entrada_evento_fkey FOREIGN KEY (id_boliche, id_evento) REFERENCES public.evento(id_boliche, id_evento) ON DELETE CASCADE,
    CONSTRAINT chk_entrada_tipo CHECK (tipo IN ('tanda', 'vip')),
    CONSTRAINT chk_entrada_estado CHECK (estado IN ('disponible', 'agotada', 'no_disponible')),
    CONSTRAINT chk_entrada_precios CHECK (precio_virtual >= 0 AND precio_puerta >= 0),
    CONSTRAINT chk_entrada_cupo CHECK (cupo > 0)
);

CREATE UNIQUE INDEX tipo_entrada_nombre_key ON public.tipo_entrada (id_evento, lower(nombre));

-- La carta de bebidas de cada boliche. Cada bebida que se carga queda guardada; "disponible" permite sacarla de la carta sin borrarla.
CREATE TABLE public.bebida (
    id_bebida integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_boliche integer NOT NULL,
    categoria character varying(60) NOT NULL,
    nombre character varying(100) NOT NULL,
    descripcion character varying(300),
    precio integer NOT NULL,
    imagen character varying(300),
    disponible boolean NOT NULL DEFAULT true,
    fecha_creacion timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT bebida_pkey PRIMARY KEY (id_bebida),
    CONSTRAINT bebida_boliche_fkey FOREIGN KEY (id_boliche) REFERENCES public.boliche(id_boliche) ON DELETE CASCADE,
    CONSTRAINT chk_bebida_precio CHECK (precio >= 0)
);

CREATE UNIQUE INDEX bebida_nombre_key ON public.bebida (id_boliche, lower(categoria), lower(nombre));
CREATE INDEX bebida_boliche_idx ON public.bebida (id_boliche, categoria);

-- Las mesas VIP de un boliche (el catálogo). Cada evento elige cuáles ofrece esa noche (tabla de abajo).
CREATE TABLE public.mesa_vip (
    id_mesa integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_boliche integer NOT NULL,
    nombre character varying(60) NOT NULL,
    capacidad smallint NOT NULL,
    precio integer NOT NULL,
    descripcion character varying(400),
    imagen character varying(300),
    activa boolean NOT NULL DEFAULT true,
    CONSTRAINT mesa_vip_pkey PRIMARY KEY (id_mesa),
    CONSTRAINT mesa_vip_boliche_mesa_key UNIQUE (id_boliche, id_mesa),
    CONSTRAINT mesa_vip_boliche_fkey FOREIGN KEY (id_boliche) REFERENCES public.boliche(id_boliche) ON DELETE CASCADE,
    CONSTRAINT chk_mesa_capacidad CHECK (capacidad > 0),
    CONSTRAINT chk_mesa_precio CHECK (precio >= 0)
);

CREATE UNIQUE INDEX mesa_vip_nombre_key ON public.mesa_vip (id_boliche, lower(nombre));

-- Qué mesas VIP ofrece cada evento y en qué estado está cada una esa noche.
-- Las dos claves compuestas hacen que el evento y la mesa sean del mismo boliche.
CREATE TABLE public.evento_mesa_vip (
    id_boliche integer NOT NULL,
    id_evento integer NOT NULL,
    id_mesa integer NOT NULL,
    estado character varying(12) NOT NULL DEFAULT 'disponible',
    CONSTRAINT evento_mesa_vip_pkey PRIMARY KEY (id_evento, id_mesa),
    CONSTRAINT evento_mesa_vip_evento_fkey FOREIGN KEY (id_boliche, id_evento) REFERENCES public.evento(id_boliche, id_evento) ON DELETE CASCADE,
    CONSTRAINT evento_mesa_vip_mesa_fkey FOREIGN KEY (id_boliche, id_mesa) REFERENCES public.mesa_vip(id_boliche, id_mesa) ON DELETE CASCADE,
    CONSTRAINT chk_evento_mesa_estado CHECK (estado IN ('disponible', 'reservada'))
);

-- Colores de la página de cada boliche: una fila por boliche y por modo. Sin fila, rigen los valores por defecto (negro y dorado).
CREATE TABLE public.boliche_tema (
    id_boliche integer NOT NULL,
    modo character varying(7) NOT NULL,
    fondo character(7) NOT NULL,
    tarjetas character(7) NOT NULL,
    texto character(7) NOT NULL,
    acento character(7) NOT NULL,
    CONSTRAINT boliche_tema_pkey PRIMARY KEY (id_boliche, modo),
    CONSTRAINT boliche_tema_boliche_fkey FOREIGN KEY (id_boliche) REFERENCES public.boliche(id_boliche) ON DELETE CASCADE,
    CONSTRAINT chk_tema_modo CHECK (modo IN ('claro', 'oscuro')),
    CONSTRAINT chk_tema_colores CHECK (fondo ~ '^#[0-9A-F]{6}$' AND tarjetas ~ '^#[0-9A-F]{6}$' AND texto ~ '^#[0-9A-F]{6}$' AND acento ~ '^#[0-9A-F]{6}$')
);

-- =====================================================
-- 4. REGLAS QUE APLICA LA BASE
-- =====================================================

-- Solo un usuario con rol admin puede ser admin de un boliche.
CREATE FUNCTION public.validar_boliche_admin() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM public.usuario WHERE id_usuario = NEW.id_usuario AND rol = 'admin') THEN
        RAISE EXCEPTION 'Solo un usuario con rol admin puede administrar un boliche';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_validar_boliche_admin BEFORE INSERT OR UPDATE ON public.boliche_admin
    FOR EACH ROW EXECUTE FUNCTION public.validar_boliche_admin();

-- El rol del equipo tiene que coincidir con el del usuario, y el manager de un RRPP tiene que ser un rrpp_manager.
CREATE FUNCTION public.validar_boliche_equipo() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM public.usuario WHERE id_usuario = NEW.id_usuario AND rol = NEW.rol) THEN
        RAISE EXCEPTION 'El rol del equipo no coincide con el rol del usuario';
    END IF;
    IF NEW.id_manager IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM public.boliche_equipo WHERE id_boliche = NEW.id_boliche AND id_usuario = NEW.id_manager AND rol = 'rrpp_manager'
    ) THEN
        RAISE EXCEPTION 'El manager indicado no es un RRPP manager de este boliche';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_validar_boliche_equipo BEFORE INSERT OR UPDATE ON public.boliche_equipo
    FOR EACH ROW EXECUTE FUNCTION public.validar_boliche_equipo();

-- El creador de un evento tiene que ser alguien con acceso a ese boliche (superadmin, su admin o su manager).
CREATE FUNCTION public.validar_evento_creador() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.id_creador IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM public.usuario u WHERE u.id_usuario = NEW.id_creador AND (
            u.rol = 'superadmin'
            OR EXISTS (SELECT 1 FROM public.boliche_admin a WHERE a.id_usuario = u.id_usuario AND a.id_boliche = NEW.id_boliche)
            OR EXISTS (SELECT 1 FROM public.boliche_equipo q WHERE q.id_usuario = u.id_usuario AND q.id_boliche = NEW.id_boliche AND q.rol = 'rrpp_manager')
        )
    ) THEN
        RAISE EXCEPTION 'Quien crea el evento no pertenece a este boliche';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_validar_evento_creador BEFORE INSERT ON public.evento
    FOR EACH ROW EXECUTE FUNCTION public.validar_evento_creador();

-- Un boliche puede tener hasta 10 fotos.
CREATE FUNCTION public.validar_boliche_foto() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF (SELECT count(*) FROM public.boliche_foto WHERE id_boliche = NEW.id_boliche) >= 10 THEN
        RAISE EXCEPTION 'Un boliche puede tener hasta 10 fotos: borrá alguna para subir otra';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_validar_boliche_foto BEFORE INSERT ON public.boliche_foto
    FOR EACH ROW EXECUTE FUNCTION public.validar_boliche_foto();

-- La suma de los cupos de las entradas de un evento no puede superar la capacidad del boliche.
CREATE FUNCTION public.validar_cupo_evento() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    capacidad integer;
    usado integer;
BEGIN
    SELECT b.capacidad INTO capacidad FROM public.boliche b WHERE b.id_boliche = NEW.id_boliche;
    IF capacidad IS NULL THEN
        RAISE EXCEPTION 'Antes de crear entradas hay que definir la capacidad del boliche';
    END IF;
    SELECT COALESCE(sum(cupo), 0) INTO usado FROM public.tipo_entrada
     WHERE id_evento = NEW.id_evento AND id_tipo_entrada IS DISTINCT FROM NEW.id_tipo_entrada;
    IF usado + NEW.cupo > capacidad THEN
        RAISE EXCEPTION 'La suma de los cupos (%) supera la capacidad del boliche (%)', usado + NEW.cupo, capacidad;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_validar_cupo_evento BEFORE INSERT OR UPDATE OF cupo, id_evento ON public.tipo_entrada
    FOR EACH ROW EXECUTE FUNCTION public.validar_cupo_evento();

-- No se puede bajar (ni borrar) la capacidad del boliche por debajo de lo que ya reparten las entradas de algún evento.
CREATE FUNCTION public.validar_capacidad_boliche() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    maximo integer;
BEGIN
    SELECT COALESCE(max(total), 0) INTO maximo FROM (
        SELECT sum(cupo) AS total FROM public.tipo_entrada WHERE id_boliche = NEW.id_boliche GROUP BY id_evento
    ) por_evento;
    IF maximo > 0 AND (NEW.capacidad IS NULL OR NEW.capacidad < maximo) THEN
        RAISE EXCEPTION 'La capacidad no puede ser menor a los cupos ya repartidos en las entradas (%)', maximo;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_validar_capacidad_boliche BEFORE UPDATE OF capacidad ON public.boliche
    FOR EACH ROW EXECUTE FUNCTION public.validar_capacidad_boliche();

COMMIT;
