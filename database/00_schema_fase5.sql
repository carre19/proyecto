-- =====================================================================================================
-- Fase 5: personal externo, proveedores, gastos e ingresos. Todo lo gestiona el admin de cada boliche.
-- Se aplica después de la fase 4; se puede repetir. Montos en pesos enteros.
-- =====================================================================================================
BEGIN;

-- Personal externo: no tiene panel propio, el admin lleva una ficha por persona (se va completando con el tiempo).
-- rol_local: qué hace en el local. monto_cobro: cuánto cobra, según cobro_tipo (por evento, por hora o por mes).
CREATE TABLE IF NOT EXISTS public.personal (
    id_personal integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_boliche integer NOT NULL,
    nombre character varying(100) NOT NULL,
    apellido character varying(100) NOT NULL,
    nombre_completo character varying(201) GENERATED ALWAYS AS (nombre || ' ' || apellido) STORED,
    rol_local character varying(20) NOT NULL,
    monto_cobro integer,
    cobro_tipo character varying(10) NOT NULL DEFAULT 'por_evento',
    notas text,
    activo boolean NOT NULL DEFAULT true,
    creado_en timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT personal_pkey PRIMARY KEY (id_personal),
    CONSTRAINT personal_boliche_personal_key UNIQUE (id_boliche, id_personal),
    CONSTRAINT personal_boliche_fkey FOREIGN KEY (id_boliche) REFERENCES public.boliche(id_boliche) ON DELETE CASCADE,
    CONSTRAINT chk_personal_rol CHECK (rol_local IN ('encargado', 'puerta', 'boleteria', 'seguridad', 'barman', 'limpieza', 'dj_artista', 'guardarropa', 'mozo_vip')),
    CONSTRAINT chk_personal_cobro_tipo CHECK (cobro_tipo IN ('por_evento', 'por_hora', 'mensual')),
    CONSTRAINT chk_personal_monto CHECK (monto_cobro IS NULL OR monto_cobro >= 0)
);
CREATE INDEX IF NOT EXISTS personal_boliche_idx ON public.personal (id_boliche, rol_local);

-- Los métodos de contacto que el admin va agregando a cada ficha (teléfono, WhatsApp, email, Instagram...).
CREATE TABLE IF NOT EXISTS public.personal_contacto (
    id_contacto integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_boliche integer NOT NULL,
    id_personal integer NOT NULL,
    tipo character varying(10) NOT NULL,
    valor character varying(150) NOT NULL,
    CONSTRAINT personal_contacto_pkey PRIMARY KEY (id_contacto),
    CONSTRAINT personal_contacto_personal_fkey FOREIGN KEY (id_boliche, id_personal) REFERENCES public.personal(id_boliche, id_personal) ON DELETE CASCADE,
    CONSTRAINT chk_contacto_tipo CHECK (tipo IN ('telefono', 'whatsapp', 'email', 'instagram', 'otro'))
);

-- Cuándo estuvo cada persona: en qué eventos trabajó y cuánto se le pagó por esa noche.
CREATE TABLE IF NOT EXISTS public.personal_evento (
    id_boliche integer NOT NULL,
    id_evento integer NOT NULL,
    id_personal integer NOT NULL,
    monto_pagado integer,
    nota character varying(300),
    CONSTRAINT personal_evento_pkey PRIMARY KEY (id_evento, id_personal),
    CONSTRAINT personal_evento_evento_fkey FOREIGN KEY (id_boliche, id_evento) REFERENCES public.evento(id_boliche, id_evento) ON DELETE CASCADE,
    CONSTRAINT personal_evento_personal_fkey FOREIGN KEY (id_boliche, id_personal) REFERENCES public.personal(id_boliche, id_personal) ON DELETE CASCADE,
    CONSTRAINT chk_personal_evento_monto CHECK (monto_pagado IS NULL OR monto_pagado >= 0)
);

-- Cuánta gente de seguridad, limpieza y barman va a cada evento.
CREATE TABLE IF NOT EXISTS public.evento_dotacion (
    id_boliche integer NOT NULL,
    id_evento integer NOT NULL,
    rol_local character varying(20) NOT NULL,
    cantidad smallint NOT NULL,
    CONSTRAINT evento_dotacion_pkey PRIMARY KEY (id_evento, rol_local),
    CONSTRAINT evento_dotacion_evento_fkey FOREIGN KEY (id_boliche, id_evento) REFERENCES public.evento(id_boliche, id_evento) ON DELETE CASCADE,
    CONSTRAINT chk_dotacion_rol CHECK (rol_local IN ('seguridad', 'limpieza', 'barman')),
    CONSTRAINT chk_dotacion_cantidad CHECK (cantidad >= 0 AND cantidad <= 500)
);

CREATE TABLE IF NOT EXISTS public.proveedor (
    id_proveedor integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_boliche integer NOT NULL,
    nombre character varying(120) NOT NULL,
    rubro character varying(80),
    contacto character varying(200),
    notas text,
    activo boolean NOT NULL DEFAULT true,
    CONSTRAINT proveedor_pkey PRIMARY KEY (id_proveedor),
    CONSTRAINT proveedor_boliche_proveedor_key UNIQUE (id_boliche, id_proveedor),
    CONSTRAINT proveedor_boliche_fkey FOREIGN KEY (id_boliche) REFERENCES public.boliche(id_boliche) ON DELETE CASCADE
);
CREATE UNIQUE INDEX IF NOT EXISTS proveedor_nombre_key ON public.proveedor (id_boliche, lower(nombre));

-- Gastos del local: de una noche (id_evento) o generales (id_evento NULL); pueden ser de un proveedor.
CREATE TABLE IF NOT EXISTS public.gasto (
    id_gasto integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_boliche integer NOT NULL,
    id_evento integer,
    id_proveedor integer,
    concepto character varying(150) NOT NULL,
    categoria character varying(60),
    monto integer NOT NULL,
    fecha date NOT NULL DEFAULT CURRENT_DATE,
    nota text,
    creado_por integer,
    creado_en timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT gasto_pkey PRIMARY KEY (id_gasto),
    CONSTRAINT gasto_boliche_fkey FOREIGN KEY (id_boliche) REFERENCES public.boliche(id_boliche) ON DELETE CASCADE,
    CONSTRAINT gasto_evento_fkey FOREIGN KEY (id_boliche, id_evento) REFERENCES public.evento(id_boliche, id_evento) ON DELETE SET NULL (id_evento),
    CONSTRAINT gasto_proveedor_fkey FOREIGN KEY (id_boliche, id_proveedor) REFERENCES public.proveedor(id_boliche, id_proveedor) ON DELETE SET NULL (id_proveedor),
    CONSTRAINT gasto_creador_fkey FOREIGN KEY (creado_por) REFERENCES public.usuario(id_usuario) ON DELETE SET NULL,
    CONSTRAINT chk_gasto_monto CHECK (monto > 0)
);
CREATE INDEX IF NOT EXISTS gasto_boliche_idx ON public.gasto (id_boliche, fecha);

-- Ingresos del local que no son entradas (barra, guardarropa, mesas...). Las entradas pagadas se suman solas en los resúmenes.
CREATE TABLE IF NOT EXISTS public.ingreso (
    id_ingreso integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_boliche integer NOT NULL,
    id_evento integer,
    concepto character varying(150) NOT NULL,
    categoria character varying(60),
    monto integer NOT NULL,
    fecha date NOT NULL DEFAULT CURRENT_DATE,
    nota text,
    creado_por integer,
    creado_en timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT ingreso_pkey PRIMARY KEY (id_ingreso),
    CONSTRAINT ingreso_boliche_fkey FOREIGN KEY (id_boliche) REFERENCES public.boliche(id_boliche) ON DELETE CASCADE,
    CONSTRAINT ingreso_evento_fkey FOREIGN KEY (id_boliche, id_evento) REFERENCES public.evento(id_boliche, id_evento) ON DELETE SET NULL (id_evento),
    CONSTRAINT ingreso_creador_fkey FOREIGN KEY (creado_por) REFERENCES public.usuario(id_usuario) ON DELETE SET NULL,
    CONSTRAINT chk_ingreso_monto CHECK (monto > 0)
);
CREATE INDEX IF NOT EXISTS ingreso_boliche_idx ON public.ingreso (id_boliche, fecha);

COMMIT;
