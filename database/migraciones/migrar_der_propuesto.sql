-- 2. EVENTO: ESTADOS, ORGANIZADOR, FECHA Y SEDE
-- =====================================================

-- Organizador responsable de cada evento.
ALTER TABLE public.evento
    ADD COLUMN IF NOT EXISTS id_organizador INTEGER
        REFERENCES public.personal(id_personal)
        ON DELETE NO ACTION;

-- La fecha puede estar pendiente al recibir la solicitud.
ALTER TABLE public.evento
    ALTER COLUMN fecha DROP NOT NULL;

-- Estado de la sede: confirmada o pendiente.
ALTER TABLE public.evento
    ADD COLUMN IF NOT EXISTS estado_sede VARCHAR(15) NOT NULL DEFAULT 'pendiente';

ALTER TABLE public.evento
    DROP CONSTRAINT IF EXISTS chk_evento_estado_sede;

ALTER TABLE public.evento
    ADD CONSTRAINT chk_evento_estado_sede
    CHECK (estado_sede IN ('pendiente', 'confirmada'));

-- Migrar los estados anteriores a los nuevos.
UPDATE public.evento
SET estado = CASE estado
    WHEN 'solicitado' THEN 'recibida'
    WHEN 'con_propuesta' THEN 'propuesta_enviada'
    ELSE estado
END;

ALTER TABLE public.evento
    DROP CONSTRAINT IF EXISTS chk_evento_estado;

ALTER TABLE public.evento
    ADD CONSTRAINT chk_evento_estado
    CHECK (estado IN (
        'recibida',
        'en_evaluacion',
        'propuesta_enviada',
        'aceptada',
        'rechazada',
        'confirmado',
        'preparacion',
        'realizado',
        'cancelado'
    )) NOT VALID;

-- Exigir datos completos al aceptar, confirmar o avanzar el evento.
CREATE OR REPLACE FUNCTION public.validar_evento_confirmado()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.estado IN (
        'aceptada',
        'confirmado',
        'preparacion',
        'realizado'
    ) THEN
        IF NEW.fecha IS NULL
           OR NEW.sede_prevista IS NULL
           OR TRIM(NEW.sede_prevista) = ''
           OR NEW.cant_asistentes_estimada IS NULL
           OR NEW.cant_asistentes_estimada <= 0 THEN
            RAISE EXCEPTION
                'Para aceptar o confirmar el evento se requiere fecha, sede y cantidad estimada de asistentes válida.';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validar_evento_confirmado
ON public.evento;

CREATE TRIGGER trg_validar_evento_confirmado
BEFORE INSERT OR UPDATE OF estado, fecha,
    sede_prevista, cant_asistentes_estimada
ON public.evento
FOR EACH ROW
EXECUTE FUNCTION public.validar_evento_confirmado();

-- =====================================================
-- 3. PROPUESTA: APROBACIÓN, ENVÍO Y RECHAZO
-- =====================================================

ALTER TABLE public.propuesta
    ADD COLUMN IF NOT EXISTS aprobado_por INTEGER
        REFERENCES public.personal(id_personal)
        ON DELETE NO ACTION,
    ADD COLUMN IF NOT EXISTS fecha_aprobacion TIMESTAMP WITH TIME ZONE,
    ADD COLUMN IF NOT EXISTS motivo_rechazo VARCHAR(500);

ALTER TABLE public.propuesta
    DROP CONSTRAINT IF EXISTS chk_propuesta_estado;

ALTER TABLE public.propuesta
    ADD CONSTRAINT chk_propuesta_estado
    CHECK (estado IN (
        'borrador',
        'pendiente_aprobacion',
        'aprobada',
        'enviada',
        'en_negociacion',
        'aceptada',
        'rechazada'
    )) NOT VALID;

-- Una propuesta aprobada no se cambia sin nueva revisión:
-- si se modifican los importes o las condiciones, vuelve a
-- pendiente_aprobacion y se borra la aprobación anterior.
-- Se asume que propuesta tiene la columna "condiciones"; ajustar
-- la lista de columnas vigiladas si el nombre es otro.
CREATE OR REPLACE FUNCTION public.reabrir_propuesta_modificada()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.estado IN ('aprobada', 'enviada')
       AND NEW.estado = OLD.estado
       AND (to_jsonb(NEW) - ARRAY['estado', 'aprobado_por', 'fecha_aprobacion', 'motivo_rechazo'])
           IS DISTINCT FROM
           (to_jsonb(OLD) - ARRAY['estado', 'aprobado_por', 'fecha_aprobacion', 'motivo_rechazo'])
    THEN
        NEW.estado := 'pendiente_aprobacion';
        NEW.aprobado_por := NULL;
        NEW.fecha_aprobacion := NULL;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_reabrir_propuesta_modificada
ON public.propuesta;

CREATE TRIGGER trg_reabrir_propuesta_modificada
BEFORE UPDATE ON public.propuesta
FOR EACH ROW
EXECUTE FUNCTION public.reabrir_propuesta_modificada();

