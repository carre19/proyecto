CREATE TABLE IF NOT EXISTS public.rol (
    id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(30) NOT NULL UNIQUE
);

INSERT INTO public.rol (nombre)
VALUES ('responsable'), ('organizador'), ('coordinador')
ON CONFLICT (nombre) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.personal_rol (
    id_personal INTEGER NOT NULL
        REFERENCES public.personal(id_personal)
        ON DELETE NO ACTION,
    id_rol INTEGER NOT NULL
        REFERENCES public.rol(id_rol)
        ON DELETE NO ACTION,
    PRIMARY KEY (id_personal, id_rol)
);

-- Acceso identificado: auth propio con JWT. Las credenciales viven en
-- public.usuario (contraseña hasheada con bcrypt) y cada personal se vincula a un usuario.
CREATE TABLE IF NOT EXISTS public.usuario (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE public.personal
    ADD COLUMN IF NOT EXISTS usuario_id INTEGER UNIQUE
        REFERENCES public.usuario(id_usuario) ON DELETE SET NULL;

