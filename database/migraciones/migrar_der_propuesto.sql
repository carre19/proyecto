    ADD COLUMN IF NOT EXISTS motivo_cancelacion VARCHAR(500),
    ADD COLUMN IF NOT EXISTS registrado_por INTEGER
        REFERENCES public.personal(id_personal)
        ON DELETE NO ACTION;

