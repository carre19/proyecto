    CHECK (origen_cancelacion IS NULL
           OR origen_cancelacion IN ('cliente', 'organizadora'));

-- =====================================================
-- 6. HISTORIAL DE CAMBIOS DEL EVENTO
-- =====================================================

CREATE TABLE IF NOT EXISTS public.cambio_evento (
    id_cambio INTEGER GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    id_evento INTEGER NOT NULL
        REFERENCES public.evento(id_evento)
        ON DELETE NO ACTION,
    fecha_registro TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT NOW(),
    tipo_cambio VARCHAR(50) NOT NULL,
    descripcion VARCHAR(500) NOT NULL,
    registrado_por INTEGER NOT NULL
        REFERENCES public.personal(id_personal)
        ON DELETE NO ACTION,
    situacion_compromisos VARCHAR(500)
);

-- =====================================================
-- 7. TAREAS: ESTADOS, FECHA OBLIGATORIA Y VÍNCULO AL SERVICIO
-- =====================================================

UPDATE public.tarea
SET estado = 'terminada'
WHERE estado = 'completada';

ALTER TABLE public.tarea
    DROP CONSTRAINT IF EXISTS chk_tarea_estado;

ALTER TABLE public.tarea
    ADD CONSTRAINT chk_tarea_estado
    CHECK (estado IN (
        'pendiente',
        'en_curso',
        'terminada',
        'cancelada'
    )) NOT VALID;

-- fecha_prevista obligatoria. NOT VALID: se exige en filas nuevas
-- o modificadas, sin romper las tareas viejas sin fecha. Cuando se
-- completen, correr: ALTER TABLE public.tarea VALIDATE CONSTRAINT chk_tarea_fecha_prevista;
ALTER TABLE public.tarea
    DROP CONSTRAINT IF EXISTS chk_tarea_fecha_prevista;

ALTER TABLE public.tarea
    ADD CONSTRAINT chk_tarea_fecha_prevista
    CHECK (fecha_prevista IS NOT NULL) NOT VALID;

-- Opcional: a qué servicio de la propuesta corresponde la tarea.
-- Se asume que la PK de detalle_propuesta es id_detalle.
ALTER TABLE public.tarea
    ADD COLUMN IF NOT EXISTS id_detalle INTEGER
        REFERENCES public.detalle_propuesta(id_detalle)
        ON DELETE NO ACTION;

-- "Vencida" no se guarda: se calcula en la consulta
-- (fecha_prevista < CURRENT_DATE AND estado <> 'terminada').

-- =====================================================
-- 8. CLIENTE: SIN DNI, TELÉFONO OBLIGATORIO, EMAIL OPCIONAL
-- =====================================================

ALTER TABLE public.cliente
    DROP CONSTRAINT IF EXISTS chk_cliente_contacto;

ALTER TABLE public.cliente
    DROP COLUMN IF EXISTS dni;

-- NOT VALID: se exige en filas nuevas o modificadas; los clientes
-- viejos sin teléfono hay que completarlos y luego validar.
ALTER TABLE public.cliente
    DROP CONSTRAINT IF EXISTS chk_cliente_telefono;

ALTER TABLE public.cliente
    ADD CONSTRAINT chk_cliente_telefono
    CHECK (NULLIF(TRIM(telefono), '') IS NOT NULL) NOT VALID;

-- =====================================================
-- 9. AVISOS A PROVEEDORES POR CANCELACIÓN
-- (punto "a decidir con el cliente/grupo": se deja creada;
--  si no se usa, se elimina esta tabla)
-- =====================================================

CREATE TABLE IF NOT EXISTS public.aviso_proveedor_cancelacion (
    id_aviso INTEGER GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    id_cierre INTEGER NOT NULL
        REFERENCES public.cierre(id_cierre)
        ON DELETE NO ACTION,
    id_proveedor INTEGER NOT NULL
        REFERENCES public.proveedor(id_proveedor)
        ON DELETE NO ACTION,
    fecha_aviso TIMESTAMP WITH TIME ZONE,
    medio VARCHAR(30),
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente',
    observaciones VARCHAR(500),
    registrado_por INTEGER
        REFERENCES public.personal(id_personal)
        ON DELETE NO ACTION,

    CONSTRAINT chk_aviso_estado
        CHECK (estado IN (
            'pendiente',
            'enviado',
            'confirmado',
            'fallido'
        ))
);

