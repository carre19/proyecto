-- =====================================================

ALTER TABLE public.detalle_propuesta
    DROP CONSTRAINT IF EXISTS chk_detalle_estado_proveedor;

ALTER TABLE public.detalle_propuesta
    ADD CONSTRAINT chk_detalle_estado_proveedor
    CHECK (estado_proveedor IN (
        'pendiente',
        'confirmado',
        'no_disponible'
    )) NOT VALID;

-- Servicio evaluado que el cliente descartó (ej.: fotografía).
-- Proveedor anterior y observaciones: reemplazos de proveedor,
-- su motivo y las condiciones acordadas para este evento.
ALTER TABLE public.detalle_propuesta
    ADD COLUMN IF NOT EXISTS descartado BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS id_proveedor_anterior INTEGER
        REFERENCES public.proveedor(id_proveedor)
        ON DELETE NO ACTION,
    ADD COLUMN IF NOT EXISTS observaciones VARCHAR(500);

