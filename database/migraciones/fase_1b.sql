-- Para bases creadas ANTES de la fase 1B (las nuevas ya lo traen en 00_schema.sql).
--   - las fotos pasan de la columna boliche.fotos a la tabla boliche_foto (se conservan; la primera queda de portada)
--   - se suman tipo_entrada, bebida, mesa_vip, evento_mesa_vip y boliche_tema, y las reglas de la base
--   - evento.imagen (el flyer) se agrega si falta
