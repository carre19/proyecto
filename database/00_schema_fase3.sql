-- =====================================================================================================
-- Fase 3: pagos. Cuenta de cobro de cada boliche, registro de pagos (con confirmación automática de transferencias),
-- pagos que hay que revisar y avisos al cliente por WhatsApp y email. Se aplica después de la fase 2; se puede repetir.
-- =====================================================================================================
BEGIN;

-- Dónde le paga el cliente al boliche: la cuenta que el admin prefiera (banco, alias o CBU).
CREATE TABLE IF NOT EXISTS public.boliche_cuenta_cobro (
    id_boliche integer NOT NULL,
    titular character varying(120) NOT NULL,
    banco character varying(80),
    alias character varying(60),
    cbu character varying(30),
    instrucciones text,
    actualizada_en timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT boliche_cuenta_cobro_pkey PRIMARY KEY (id_boliche),
    CONSTRAINT boliche_cuenta_cobro_boliche_fkey FOREIGN KEY (id_boliche) REFERENCES public.boliche(id_boliche) ON DELETE CASCADE,
    CONSTRAINT chk_cuenta_cobro_destino CHECK (alias IS NOT NULL OR cbu IS NOT NULL)
);

-- Cada pago que llegó o se registró. estado: 'confirmado' (la compra quedó paga), 'a_revisar' (llegó plata que no se pudo
-- asignar sola: monto insuficiente, compra vencida o pago repetido) o 'resuelto' (el admin ya lo revisó).
-- id_operacion es el número de la operación del banco: no se puede registrar dos veces.
CREATE TABLE IF NOT EXISTS public.pago (
    id_pago integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_boliche integer NOT NULL,
    id_compra integer NOT NULL,
    metodo character varying(15) NOT NULL,
    monto integer NOT NULL,
    id_operacion character varying(80),
    estado character varying(12) NOT NULL DEFAULT 'confirmado',
    origen character varying(10) NOT NULL,
    id_usuario integer,
    detalle character varying(300),
    recibido_en timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT pago_pkey PRIMARY KEY (id_pago),
    CONSTRAINT pago_compra_fkey FOREIGN KEY (id_boliche, id_compra) REFERENCES public.compra(id_boliche, id_compra) ON DELETE CASCADE,
    CONSTRAINT pago_usuario_fkey FOREIGN KEY (id_usuario) REFERENCES public.usuario(id_usuario) ON DELETE SET NULL,
    CONSTRAINT chk_pago_metodo CHECK (metodo IN ('transferencia', 'efectivo', 'qr')),
    CONSTRAINT chk_pago_estado CHECK (estado IN ('confirmado', 'a_revisar', 'resuelto')),
    CONSTRAINT chk_pago_origen CHECK (origen IN ('automatico', 'manual', 'puerta')),
    CONSTRAINT chk_pago_monto CHECK (monto >= 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS pago_operacion_key ON public.pago (id_operacion) WHERE id_operacion IS NOT NULL;
CREATE INDEX IF NOT EXISTS pago_boliche_idx ON public.pago (id_boliche, estado, recibido_en DESC);

-- Avisos al cliente cuando se confirma el pago. Una cola: se envían aparte (WhatsApp si dio su teléfono, email si dio su email).
-- estado: 'pendiente' -> 'enviada' | 'simulada' (no hay servicio de envío configurado, queda registrado) | 'fallida' (tras varios intentos).
CREATE TABLE IF NOT EXISTS public.notificacion (
    id_notificacion integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_boliche integer NOT NULL,
    id_compra integer NOT NULL,
    tipo character varying(20) NOT NULL DEFAULT 'pago_confirmado',
    canal character varying(10) NOT NULL,
    destino character varying(150) NOT NULL,
    asunto character varying(150),
    mensaje text NOT NULL,
    estado character varying(10) NOT NULL DEFAULT 'pendiente',
    intentos smallint NOT NULL DEFAULT 0,
    error character varying(300),
    creada_en timestamp with time zone NOT NULL DEFAULT now(),
    enviada_en timestamp with time zone,
    CONSTRAINT notificacion_pkey PRIMARY KEY (id_notificacion),
    CONSTRAINT notificacion_compra_fkey FOREIGN KEY (id_boliche, id_compra) REFERENCES public.compra(id_boliche, id_compra) ON DELETE CASCADE,
    CONSTRAINT notificacion_unica_key UNIQUE (id_compra, tipo, canal),
    CONSTRAINT chk_notificacion_canal CHECK (canal IN ('whatsapp', 'email')),
    CONSTRAINT chk_notificacion_estado CHECK (estado IN ('pendiente', 'enviada', 'simulada', 'fallida'))
);
CREATE INDEX IF NOT EXISTS notificacion_pendiente_idx ON public.notificacion (creada_en) WHERE estado = 'pendiente';

COMMIT;
